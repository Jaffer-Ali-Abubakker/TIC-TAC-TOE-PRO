<#
.SYNOPSIS
  Creates (or updates) the .env file for Tic-Tac-Toe Pro by asking the
  Supabase Management API for your project's URL and publishable key.

.DESCRIPTION
  The Supabase personal access token is read with a hidden prompt and is used
  only in memory. It is never written to disk, never printed and never passed
  as a command line argument (so it never lands in your shell history).

  The token needs the "read:organization" scope - the default personal access
  token is enough.

.EXAMPLE
  pwsh -File scripts/setup-env.ps1
  pwsh -File scripts/setup-env.ps1 -ProjectRef abcdefghijklmnop -AppUrl https://my-app.vercel.app
#>
[CmdletBinding()]
param(
  # Skip the project picker and use this project ref (the part of your
  # project URL between https:// and .supabase.co).
  [string] $ProjectRef,

  # The public URL of the deployed application. Used to build invite links.
  [string] $AppUrl = 'https://tic-tac-toe-pro.vercel.app'
)

$ErrorActionPreference = 'Stop'

$ManagementApi = 'https://api.supabase.com'
$TokenUrl = 'https://supabase.com/dashboard/account/tokens'

function Write-Step($message) { Write-Host "==> $message" -ForegroundColor Cyan }
function Write-Ok($message) { Write-Host "    OK  $message" -ForegroundColor Green }
function Write-Warn($message) { Write-Host "    !!  $message" -ForegroundColor Yellow }

# ---------------------------------------------------------------------------
# 1. Personal access token
# ---------------------------------------------------------------------------
Write-Step 'Supabase personal access token'
Write-Host "    Create one at: $TokenUrl" -ForegroundColor DarkGray
Write-Host "    (it is only held in memory for this script)" -ForegroundColor DarkGray

$secure = Read-Host '    Paste your token (input hidden)' -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
try {
  $token = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
} finally {
  [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
}

if ([string]::IsNullOrWhiteSpace($token)) {
  throw 'No token entered. Aborting.'
}

$headers = @{
  Authorization  = "Bearer $token"
  'Content-Type' = 'application/json'
}

function Invoke-SupabaseApi([string] $path) {
  try {
    return Invoke-RestMethod -Uri "$ManagementApi$path" -Headers $headers -Method Get -ErrorAction Stop
  } catch {
    $status = $null
    try { $status = $_.Exception.Response.StatusCode.value__ } catch { }
    if ($status -eq 401 -or $status -eq 403) {
      throw 'The access token was rejected (401/403). Generate a new personal access token and make sure it has the "read:organization" scope.'
    }
    throw "Supabase API request failed: $($_.Exception.Message)"
  }
}

# ---------------------------------------------------------------------------
# 2. Project
# ---------------------------------------------------------------------------
if (-not $ProjectRef) {
  Write-Step 'Looking up your projects'
  $projects = @(Invoke-SupabaseApi '/v1/projects')

  if ($projects.Count -eq 0) {
    throw 'No Supabase projects were returned for this account.'
  }

  Write-Host ''
  for ($i = 0; $i -lt $projects.Count; $i++) {
    $p = $projects[$i]
    Write-Host ("    [{0}] {1}  ({2})" -f ($i + 1), $p.name, $p.id)
  }
  Write-Host ''

  $choice = Read-Host '    Which project is Tic-Tac-Toe Pro? (number, or leave blank for the first)'
  if ([string]::IsNullOrWhiteSpace($choice)) { $choice = '1' }
  $index = [int] $choice - 1
  if ($index -lt 0 -or $index -ge $projects.Count) { throw "No project with number $choice." }
  $ProjectRef = $projects[$index].id
}

Write-Ok "Project ref: $ProjectRef"

# ---------------------------------------------------------------------------
# 3. API keys
# ---------------------------------------------------------------------------
Write-Step 'Fetching the publishable key'
$keys = @(Invoke-SupabaseApi "/v1/projects/$ProjectRef/api-keys")

$publishable = $keys | Where-Object { $_.type -eq 'publishable' } | Select-Object -First 1
if (-not $publishable) {
  $publishable = $keys | Where-Object { $_.type -eq 'anon' } | Select-Object -First 1
}
if (-not $publishable) {
  throw 'No publishable (or anon) key was returned for this project.'
}

$publishableKey = $publishable.api_key
Write-Ok "Publishable key: $($publishableKey.Substring(0, 14))..."

# ---------------------------------------------------------------------------
# 4. Write .env
# ---------------------------------------------------------------------------
$projectUrl = "https://$ProjectRef.supabase.co"

$envPath = Join-Path (Split-Path -Parent $PSScriptRoot) '.env'
$content = @"
# Generated by scripts/setup-env.ps1
# These values are PUBLIC browser configuration - they are bundled into the
# JavaScript every visitor downloads. Never put a service-role / secret key here.
#
# Regenerate with:  pwsh -File scripts/setup-env.ps1

VITE_SUPABASE_URL=$projectUrl
VITE_SUPABASE_PUBLISHABLE_KEY=$publishableKey
VITE_APP_URL=$AppUrl
"@

Set-Content -LiteralPath $envPath -Value $content -Encoding utf8
Write-Ok "Wrote $envPath"

Write-Host ''
Write-Host 'Next:' -ForegroundColor Cyan
Write-Host '  1. Restart the dev server so Vite picks up the new variables:'
Write-Host '       npm run dev'
Write-Host '  2. Open the Online tab - the setup notice should be gone.'
Write-Host "  3. If you deploy, set the same three variables in the Vercel dashboard."
Write-Host ''
Write-Host "VITE_APP_URL is currently $AppUrl - change it if your domain differs." -ForegroundColor DarkGray
Write-Host ''
